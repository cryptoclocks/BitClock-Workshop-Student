void setupPage8()
{
  img.setTextColor(TFT_BLACK, TFT_WHITE);
  img.setColorDepth(1);
  img2.setColorDepth(1);
  e.setColorDepth(1);
  e2.setColorDepth(1);

  img.createSprite(320, 240);
  img2.createSprite(33, 35);
  e.createSprite(eW, eH);
  e2.createSprite(eW, eH);

 

  // อ่าน top score จากไฟล์ JSON
  File file = SD.open("/"+firmwareVersion+"/system/data/topScore.json", FILE_READ);
  if (file) {
    DynamicJsonDocument doc(512);
    DeserializationError error = deserializeJson(doc, file);
    file.close();

    if (error) {
      Serial.println("Failed to parse /" + firmwareVersion +"/system/data/topScore.json");
      topScore = 0; // กำหนดค่าเริ่มต้นหากไฟล์อ่านไม่ได้
    } else {
      topScore = doc["topScore"] | 0; // อ่านค่า topScore จาก JSON
    }
  } else {
    Serial.println("Failed to open /" + firmwareVersion +"/system/data/topScore.json");
    topScore = 0; // กำหนดค่าเริ่มต้นหากไม่พบไฟล์
  }

  showStartScreen();
  gameRun = 0 ;

  delay(100);
}



void drawS(int x, int y, int frame) {
  img.fillSprite(TFT_WHITE);
  img.drawLine(0, 134, 320, 134, TFT_BLACK);

  for (int i = 0; i < 6; i++) {
    img.drawLine(linesX[i], 137, linesX[i] + linesW[i], 137, TFT_BLACK);
    linesX[i] = linesX[i] - sped;
    if (linesX[i] < -14) {
      linesX[i] = random(325, 480);
      linesW[i] = random(1, 14);
    }
    img.drawLine(linesX2[i], 148, linesX2[i] + linesW2[i], 148, TFT_BLACK);
    linesX2[i] = linesX2[i] - sped;
    if (linesX2[i] < -14) {
      linesX2[i] = random(325, 480);
      linesW2[i] = random(1, 14);
    }
  }
  for (int j = 0; j < 2; j++) {
    img.drawXBitmap(clouds[j], 70, cloud, 38, 11, TFT_BLACK, TFT_WHITE);
    clouds[j] = clouds[j] - cloudSpeed;
    if (clouds[j] < -40)
      clouds[j] = random(324, 444);
  }

  for (int n = 0; n < 2; n++) {
    img.drawXBitmap(bumps[n], 130, bump[bumpsF[n]], 34, 5, TFT_BLACK, TFT_WHITE);
    bumps[n] = bumps[n] - sped;
    if (bumps[n] < -40) {
      int newBumpPosition;
      newBumpPosition = random(324, 720);
      if (abs(newBumpPosition - bumps[1 - n]) < 320)
      {
        newBumpPosition = bumps[1 - n] + 320 ;
      }


      bumps[n] = newBumpPosition;
      bumpsF[n] = random(0, 2);
    }
  }

  for (int m = 0; m < 2; m++) {
    eX[m] = eX[m] - sped;
    if (eX[m] < -20) {
      int newEXPosition;

      newEXPosition = random(320, 720);
      if (abs(newEXPosition - eX[1 - m]) < 320)
      {
        newEXPosition = eX[1 - m] + 320 ;
      }

      eX[m] = newEXPosition;
      ef[m] = random(0, 2);
    }
  }

  e.drawXBitmap(0, 0, enemy[0], eW, eH, TFT_BLACK, TFT_WHITE);
  e2.drawXBitmap(0, 0, enemy[1], eW, eH, TFT_BLACK, TFT_WHITE);
  img2.drawXBitmap(0, 0, dino[frame], 33, 35, TFT_BLACK, TFT_WHITE);

  e.pushToSprite(&img, eX[0], 106, TFT_WHITE);
  e2.pushToSprite(&img, eX[1], 106, TFT_WHITE);
  img2.pushToSprite(&img, x, y + 50, TFT_WHITE);

  score = (millis() - startTime) / 120; // คำนวณคะแนนโดยใช้ startTime
  img.drawString(String(score), 284, 0, 2);
  img.drawString("Top: " + String(topScore), 10, 0, 2); // แสดง top score
  img.pushSprite(0, 0);

  if (score > t + 40) { // ลดค่าเกณฑ์ในการตรวจสอบการเพิ่มความเร็ว
    t = score;
    sped = sped + 0.2; // เพิ่มอัตราการเพิ่มความเร็ว
    dir = -sped;
  }
}


void checkColision() {
  for (int i = 0; i < 2; i++) {
    if (eX[i] < x + dinoW / 2 && eX[i] > x && y > 25) {
      gameRun = 0;
      tft.fillRect(0, 30, 320, 110, TFT_WHITE);
      tft.drawXBitmap(45, 60, gameover, 223, 100, TFT_BLACK, TFT_WHITE);
      delay(500);

      // บันทึกคะแนนลงไฟล์ถ้าคะแนนมากกว่า top score
      if (score > topScore) {
        topScore = score;

        // สร้างอ็อบเจ็กต์ JSON
        DynamicJsonDocument doc(512);
        doc["game"] = "Dino Run"; // ชื่อเกม
        doc["topScore"] = topScore; // คะแนนสูงสุด

        // เปิดไฟล์ JSON สำหรับเขียนข้อมูล
        File file = SD.open("/"+firmwareVersion+"/system/data/topScore.json", FILE_WRITE);
        if (file) {
          serializeJsonPretty(doc, file);
          file.close();
          Serial.println("Top score saved successfully to /" + firmwareVersion +"/system/data/topScore.json");
        } else {
          Serial.println("Failed to open /" + firmwareVersion +"/system/data/topScore.json for writing");
        }
      }
    }
  }
}



